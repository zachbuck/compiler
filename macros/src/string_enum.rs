
//! This module centers around the derive macro `StringEnum`.
//! This macro provides derivations of `TryFrom<&str>` and `Display` through a
//! mapping provided by the user. 
//! 
//! ## Example
//! 
//! ```
//! # use macros::string_enum::StringEnum;
//! 
//! #[derive(StringEnum)]
//! # #[derive(PartialEq)]
//! enum Fruit {
//! 	#[str_mapping = "apple"]
//! 	Apple,
//! 	#[str_mapping = "orange"]
//! 	Orange,
//! 	#[str_mapping = "banana"]
//! 	Banana,
//! }
//! 
//! assert!(Fruit::try_from("apple").unwrap() == Fruit::Apple);
//! assert!(Fruit::try_from("pear").is_err());
//! assert!("banana" == &Fruit::Banana.to_string());
//! ```
//! 
//! ## Notes
//! 
//! - This macro does not at this time support anything other than `&str` literals
//! as the mapping. This behavior is enforced at compile time. While this behavior
//! is not intentional, it is not a priority for fixing, (for example to allow 
//! format!() macros).

pub use macros_internal::StringEnum;

/// This trait and its supertraits are what is implemented by the StringEnum
/// derive macro. This trait exists only as a collection of the `TryFrom<&str>`
/// and `Display` traits which are the traits generated by `#[derive(StringEnum)]`
pub trait StringEnum<'a>: TryFrom<&'a str> + std::fmt::Display {}
